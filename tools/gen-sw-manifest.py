#!/usr/bin/env python3
"""Write app/sw-manifest.js: the list of files the service worker precaches, with a
SHA-256 (first 16 hex chars) per file, and a version = hash of that whole list. Run it after any
change to a published file (and before every release):

    python tools/gen-sw-manifest.py

The service worker downloads the whole list as one set, checks every hash, and only then takes over,
so a visitor never gets a mix of old and new files.
"""
import hashlib, json, os, sys

# optional first argument: another app folder (used for testing a copy)
APP = os.path.normpath(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "app"))

# files that are not part of the site, plus the service worker files themselves
# models/ holds the background remover's model + WebAssembly runtime (hundreds of MB): fetched and cached
# by that feature on first use only, never pre-downloaded for every visitor
SKIP_DIRS = {"_test", "models"}
SKIP_NAMES = {"BUILD_NOTES.md", ".assetsignore", "_headers", "sw.js", "sw-manifest.js"}
SKIP_PREFIX = ("color/transfer",)


def files():
    out = []
    for root, dirs, names in os.walk(APP):
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS]
        for n in names:
            rel = os.path.relpath(os.path.join(root, n), APP).replace(os.sep, "/")
            if n in SKIP_NAMES or n.endswith((".bak", ".md")) or n.startswith(".") or rel.startswith(SKIP_PREFIX):
                continue
            out.append(rel)
    return sorted(out)


def main():
    table = {}
    for rel in files():
        with open(os.path.join(APP, rel), "rb") as f:
            table[rel] = hashlib.sha256(f.read()).hexdigest()[:16]
    version = hashlib.sha256(json.dumps(table, sort_keys=True).encode()).hexdigest()[:12]
    body = (
        "// Generated by tools/gen-sw-manifest.py. Do not edit.\n"
        f'self.QC_VERSION = "{version}";\n'
        f"self.QC_FILES = {json.dumps(table, indent=1, sort_keys=True)};\n"
    )
    path = os.path.join(APP, "sw-manifest.js")
    old = open(path, encoding="utf-8").read() if os.path.exists(path) else None
    if old != body:
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(body)
    print(f"sw-manifest.js: {len(table)} files, version {version}" + ("" if old != body else " (unchanged)"))


if __name__ == "__main__":
    sys.exit(main())
